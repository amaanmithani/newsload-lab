#!/usr/bin/env node
// Renders the README results section from the committed files in results/.
// Every number in the tables comes from results/<scenario>/<config>.{k6,lab}.json
// or results/machine.json; nothing is typed in by hand.
//
//   node scripts/render-results.mjs          rewrite README.md between the markers
//   node scripts/render-results.mjs --check  exit 1 if README.md is out of date (CI)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const README = path.join(ROOT, "README.md");
const START = "<!-- RESULTS:START (generated by scripts/render-results.mjs; do not edit by hand) -->";
const END = "<!-- RESULTS:END -->";
const CONFIGS = [
  ["origin", "Origin only (`/live`, dynamic)"],
  ["isr", "Next ISR only (`/news`)"],
  ["edge", "ISR + edge proxy (SWR + coalescing)"],
];

const readJson = (p) => JSON.parse(readFileSync(path.join(ROOT, p), "utf8"));

function load(scenario, config) {
  const k6Path = `results/${scenario}/${config}.k6.json`;
  const labPath = `results/${scenario}/${config}.lab.json`;
  if (!existsSync(path.join(ROOT, k6Path)) || !existsSync(path.join(ROOT, labPath))) return null;
  const k6Json = readJson(k6Path);
  return { k6: k6Json.metrics, k6Json, lab: readJson(labPath) };
}

const v = (metrics, name, stat) => metrics[name]?.values?.[stat];
const ms = (x) => (x === undefined ? "–" : x >= 1000 ? `${(x / 1000).toFixed(2)} s` : `${x.toFixed(1)} ms`);
const int = (x) => (x === undefined || x === null ? "–" : Math.round(x).toLocaleString("en-US"));
const pct = (x) => (x === undefined ? "–" : `${(x * 100).toFixed(2)}%`);
const rate = (x) => (x === undefined ? "–" : `${x.toFixed(0)}/s`);

/** Reader-only sub-metric when the scenario defines one (publish), else the global metric. */
function pick(metrics, name, scenarioTag) {
  const sub = scenarioTag ? `${name}{scenario:${scenarioTag}}` : null;
  return sub && metrics[sub] ? sub : name;
}

function targetOf(scenario, env) {
  switch (scenario) {
    case "steady":
      return `${env.RATE ?? 100}/s constant, ${env.DURATION ?? "30s"}`;
    case "spike":
      return `${env.BASE_RATE ?? 50}/s → ${env.PEAK_RATE ?? 1500}/s (hold ${env.HOLD ?? "20s"})`;
    case "publish":
      return `${env.RATE ?? 300}/s constant, ${env.DURATION ?? "40s"}, publish at ${env.PUBLISH_AT_S ?? 15} s`;
    case "herd":
      return `${env.HERD ?? 1000} VUs × 1 request, simultaneous`;
    default:
      return "";
  }
}

function loadTable(scenario) {
  const rows = [];
  let target = "";
  for (const [config, label] of CONFIGS) {
    const r = load(scenario, config);
    if (!r) continue;
    const { k6, lab } = r;
    target = targetOf(scenario, lab.k6Env);
    const tag = scenario === "publish" ? "readers" : null;
    const dur = pick(k6, "http_req_duration", tag);
    const reqs = pick(k6, "http_reqs", tag);
    const failed = pick(k6, "http_req_failed", tag);
    const count = v(k6, reqs, "count");
    const net = v(k6, "http_reqs{status:0}", "count") ?? 0;
    const fiveXX = ["500", "502", "503"].reduce((a, s) => a + (v(k6, `http_reqs{status:${s}}`, "count") ?? 0), 0);
    const reachedNext = config === "edge" ? lab.edge?.upstreamFetches : count;
    rows.push(
      `| ${label} | ${int(count)} | ${rate(v(k6, reqs, "rate"))} | ${ms(v(k6, dur, "p(50)"))} | ${ms(v(k6, dur, "p(95)"))} | ${ms(v(k6, dur, "p(99)"))} | ${pct(v(k6, failed, "rate"))} (${int(net)} net / ${int(fiveXX)} 5xx) | ${int(v(k6, "dropped_iterations", "count") ?? 0)} | ${v(k6, "vus_max", "max") !== undefined ? int(v(k6, "vus_max", "max")) : scenario === "herd" ? `${int(Number(lab.k6Env.HERD ?? 1000))} (configured; run too short to sample)` : "–"} | ${int(reachedNext)} | ${int(lab.origin.reads)} (${int(lab.origin.rejected)} rejected) | ${lab.nextEventLoopLag ? ms(lab.nextEventLoopLag.p99Ms) : "–"} | ${lab.loadAvg.peak1m.toFixed(1)}${lab.aborted ? " ⚠ aborted" : ""} |`,
    );
  }
  if (!rows.length) return `_No results yet for \`${scenario}\`. Run \`npm run lab:${scenario}\`._\n`;
  return [
    `Offered load: **${target}**.`,
    "",
    "| Configuration | Requests | Achieved rate | p50 | p95 | p99 | Error rate (network / 5xx) | Dropped iterations | Max VUs | Requests reaching Next.js | Slow-origin reads | Next.js event-loop delay p99 | Peak 1-min load avg |",
    "|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|",
    ...rows,
    "",
  ].join("\n");
}

function edgeTable() {
  const rows = [];
  for (const scenario of ["steady", "spike", "publish", "herd"]) {
    const r = load(scenario, "edge");
    if (!r?.lab.edge) continue;
    const e = r.lab.edge;
    rows.push(
      `| ${scenario} | ${int(e.requests)} | ${int(e.hit)} | ${int(e.stale)} | ${int(e.miss)} | ${int(e.coalesced)} | ${int(e.pass)} | ${int(e.upstreamFetches)} | ${int(e.backgroundRevalidations)} | ${int(e.purged)} | ${e.requests ? pct(1 - e.upstreamFetches / e.requests) : "–"} |`,
    );
  }
  if (!rows.length) return "";
  return [
    "| Scenario | Edge requests | HIT | STALE (served, refreshed in background) | MISS | COALESCED | PASS | Upstream fetches | Background revalidations | Purged entries | Offload |",
    "|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|",
    ...rows,
    "",
  ].join("\n");
}

function publishTable() {
  const rows = [];
  for (const [config, label] of CONFIGS) {
    const r = load("publish", config);
    if (!r) continue;
    const { k6, lab } = r;
    const sent = v(k6, "publish_sent_ms", "max");
    const ack = v(k6, "publish_ack_ms", "max");
    const lastStale = v(k6, "stale_start_ms", "max");
    const firstFresh = v(k6, "fresh_start_ms", "min");
    const publishCheck = r.k6Json.root_group.checks.find((c) => c.name === "publish 200");
    const published = publishCheck ? publishCheck.passes > 0 : false;
    const window = lastStale === undefined || ack === undefined ? 0 : Math.max(0, lastStale - ack);
    const publishDur = ack !== undefined && sent !== undefined ? ack - sent : undefined;
    rows.push(
      `| ${label} | ${published ? "200 OK" : "**failed**"} | ${ms(publishDur)} | ${published ? ms(window) : "n/a: story never updated"} | ${firstFresh !== undefined && sent !== undefined ? ms(firstFresh - sent) : "–"} | ${int(v(k6, "stale_after_publish", "count") ?? 0)} | ${int(v(k6, "stale_responses", "count") ?? 0)} | ${int(v(k6, "fresh_responses", "count") ?? 0)} | ${int(lab.origin.reads)} |`,
    );
  }
  if (!rows.length) return "";
  return [
    "| Configuration | Publish result | Publish call took | Staleness window after publish ack | First fresh request started after publish sent | Stale responses to requests started after publish was sent | Stale responses (total) | Fresh responses | Slow-origin reads |",
    "|---|---|--:|--:|--:|--:|--:|--:|--:|",
    ...rows,
    "",
  ].join("\n");
}

function machineBlock() {
  const p = path.join(ROOT, "results", "machine.json");
  if (!existsSync(p)) return "";
  const m = JSON.parse(readFileSync(p, "utf8"));
  return [
    `**Machine:** ${m.cpu}, ${m.logicalCpus} logical CPUs, ${m.memoryGiB} GiB RAM, ${m.os} (${m.arch}); Node ${m.node}; Next.js ${m.next}; ${m.k6}.`,
    `${m.note}`,
    "",
  ].join("\n");
}

function render() {
  const origin = load("steady", "origin")?.lab.originConfig;
  const parts = [
    START,
    "",
    machineBlock(),
    origin
      ? `Simulated origin: ${origin.latencyMs} ms per query, pool of ${origin.maxConcurrency} concurrent queries, queue timeout ${origin.queueTimeoutMs} ms (≈ ${Math.round((origin.maxConcurrency * 1000) / origin.latencyMs)} reads/s ceiling). ISR revalidate = 30 s.\n`
      : "",
    "### Steady load (normal news day, 25% of traffic on the lead story)",
    "",
    loadTable("steady"),
    "### Breaking-news spike (90% of traffic on one article)",
    "",
    loadTable("spike"),
    "### Publish during spike (story updated mid-run)",
    "",
    loadTable("publish"),
    publishTable(),
    "### Thundering herd on a cold article",
    "",
    loadTable("herd"),
    "### What the edge proxy did",
    "",
    edgeTable(),
    END,
  ];
  return parts.join("\n");
}

const readme = readFileSync(README, "utf8");
const s = readme.indexOf(START);
const e = readme.indexOf(END);
if (s < 0 || e < 0) {
  console.error("README.md is missing the RESULTS markers");
  process.exit(1);
}
const next = readme.slice(0, s) + render() + readme.slice(e + END.length);
if (process.argv.includes("--check")) {
  if (next !== readme) {
    console.error("README.md results are stale: run `npm run results:render` and commit.");
    process.exit(1);
  }
  console.log("README results are up to date with results/.");
} else {
  writeFileSync(README, next);
  console.log("README.md results section rendered from results/.");
}
